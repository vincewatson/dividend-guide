"""指数币种变体归并（数据治理 · 单一事实来源，2026-09-20 用户要求）
=================================================================
用户口径：「关于港币版取数的问题，直接取人民币版就行了。一旦出现了港币版，
          就不要再单独列出来，这样显得很傻。」

规则：**同一指数的多币种版本，站内只保留一条**（不并列、不分裂）。
      保留的那条称为「基准版」，另一版称为「变体版」，站内**不得出现变体版代码**。

基准版怎么判定（可核验，不靠猜）：
  1. Wind 全称里明确写「人民币」的那一版 = **变体**（它是折算出来的派生版）；
     例：930915.CSI 全称「中证港股通高股息投资**人民币**指数」、930840.CSI「…人民币指数」、
         930793.CSI「…人民币指数」。
  2. 若没有带「人民币」的版本，则带「港币 / (港币)」的那一版 = 变体；
     例：SPAHLVHP.SPI 全称「标普港股通低波红利**港币**指数」
         ↔ SPAHLVCP.SPI 全称「标普港股通低波红利指数」（基准）。

为什么可以安全归并：两版的**股息率数值完全相同**（2026-09-20 Wind 实测逐日比对一致），
归并只改代码与显示名，**不丢数据、不改数值**。

已核验的变体对（2026-09-20）：
  | 变体版                                       | 基准版                     | 站内处理                     |
  |--------------------------------------------|---------------------------|-----------------------------|
  | SPAHLVHP.SPI 标普港股通低波红利指数(港币)     | SPAHLVCP.SPI 标普港股通低波红利指数 | **已启用归并**（3 只ETF 159117/159118/520610）|
  | 930915.CSI  港股通高股息CNY                  | 930914.CSI 港股通高股息(HKD) | 保持现状（未启用，见下）      |
  | 930840.CSI  港股通高息精选CNY                | 930839.CSI 港股通高息精选    | 保持现状（未启用，见下）      |
  | 930793.CSI  HK银行(CNY)                      | 930792.CSI HK银行(HKD)      | 保持现状（未启用，见下）      |

✅ 其余变体对：**已与用户确认「保持现状、不做迁移」（2026-09-20）**，故本映射表不包含它们。
   已核验的变体对如下（将来若要在站内启用归并，把对应键加进 `VARIANT_TO_BASE` 即可，
   `check_data.py` 第 17 项会自动覆盖）：
     · `930915.CSI` 港股通高股息CNY  ↔  `930914.CSI` 港股通高股息(HKD)（站内现用）
       —— 站内 9 处用 930914、2 处用 930915（513530.OF / 018387.OF），两版股息率数值完全相同；
          按判定规则基准版是 930914，**用户决定保持现状**。
     · `930840.CSI` 港股通高息精选CNY ↔  `930839.CSI`（站内现用；变体版未出现于站内）
     · `930793.CSI` HK银行(CNY)       ↔  `930792.CSI`（站内现用；变体版未出现于站内）
"""

# 变体代码 → 基准版代码（站内只保留基准版）
VARIANT_TO_BASE = {
    'SPAHLVHP.SPI': 'SPAHLVCP.SPI',
}

# 基准版代码 → 站内统一简称（去掉币种/派生后缀）
BASE_NAME = {
    'SPAHLVCP.SPI': '标普港股通低波红利指数',
}


def normalize(code, name=''):
    """把币种变体归并到基准版，返回 (code, name)；非变体原样返回。"""
    code = str(code or '').strip()
    base = VARIANT_TO_BASE.get(code)
    if not base:
        return code, name
    return base, BASE_NAME.get(base) or name


def is_variant(code):
    """该代码是否为应被归并的变体版。"""
    return str(code or '').strip() in VARIANT_TO_BASE
